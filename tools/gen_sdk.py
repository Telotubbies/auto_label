"""Generate the labeldesk SDK's operation map from the FastAPI OpenAPI schema.

Usage (either cwd works):

    python tools/gen_sdk.py              # repo root
    python ../../tools/gen_sdk.py        # apps/api

The generated file is committed so `pip install` never needs the API's dependencies.
"""

from __future__ import annotations

import json
import os
import re
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
API_DIR = REPO_ROOT / "apps" / "api"
OUT = REPO_ROOT / "apps" / "sdk" / "labeldesk" / "_generated.py"
HEADER = "Generated by tools/gen_sdk.py — do not edit."

# The public developer API. Add an id here when the API grows a new /api/v1 operation.
DEVELOPER_OPERATIONS = frozenset(
    {
        "whoami",
        "list_projects",
        "list_images",
        "upload_images",
        "upload_images_v1",
        "list_versions",
        "export_version",
        "start_training",
        "get_job",
        "list_models",
        "get_model",
        "predict",
    }
)
_METHODS = ("get", "post", "put", "patch", "delete")
_PATH_PARAM = re.compile(r"\{([^}]+)\}")


def operations(spec: dict) -> dict:
    """Project the OpenAPI document down to {operationId: {method, path, scopes, params}}.

    A new /api/v1 operation that is missing from DEVELOPER_OPERATIONS fails generation instead
    of silently disappearing from the SDK.
    """
    out: dict[str, dict] = {}
    unknown: list[str] = []
    for path, item in spec.get("paths", {}).items():
        if not path.startswith("/api/v1"):
            continue
        for method, op in item.items():
            if method not in _METHODS:
                continue
            op_id = op.get("operationId")
            if op_id not in DEVELOPER_OPERATIONS:
                unknown.append(f"{method.upper()} {path} ({op_id})")
                continue
            out[op_id] = {
                "method": method,
                "path": path,
                "scopes": list(op.get("x-scopes") or []),
                "params": _PATH_PARAM.findall(path),
            }
    if unknown:
        raise ValueError("new /api/v1 operation(s) missing from DEVELOPER_OPERATIONS: " + ", ".join(unknown))
    return {op_id: out[op_id] for op_id in sorted(out)}


def render(spec: dict) -> str:
    """The committed module text for an OpenAPI document."""
    lines = [f'"""{HEADER}"""', "", "OPERATIONS = {"]
    for op_id, item in operations(spec).items():
        lines.append(f"    {json.dumps(op_id)}: {json.dumps(item)},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def openapi_spec() -> dict:
    """Import the app against a throwaway data dir so generation never touches real data."""
    os.environ.setdefault("LD_DATA_DIR", tempfile.mkdtemp(prefix="ld-gen-sdk-"))
    os.environ.setdefault("LD_EMBEDDED_WORKER", "1")
    os.environ.setdefault("LD_WORKER_TOKEN", "gen-sdk-worker-token-0123456789abcdef")
    os.environ.setdefault("LD_SAM_ENABLED", "0")
    if str(API_DIR) not in sys.path:
        sys.path.insert(0, str(API_DIR))
    from app.main import app  # imported late: env must be set first

    return app.openapi()


def main() -> int:
    spec = openapi_spec()
    text = render(spec)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(operations(spec))} operations)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
